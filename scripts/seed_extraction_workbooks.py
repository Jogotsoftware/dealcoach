# ── 6. extraction-protocol.ts (locked Platform Core prompt segment) ─────────
proto = ae['Extraction Protocol']
rules = sc_defs['Universal Rules']
lines = ["// GENERATED by scripts/seed_extraction_workbooks.py from",
         "// docs/extraction workbooks (Extraction Protocol + Universal Rules tabs).",
         "// This is the LOCKED Platform Core layer of the extraction prompt —",
         "// not org-editable anywhere. Do not hand-edit; re-run the script.",
         "",
         "export const EXTRACTION_PROTOCOL = `EXTRACTION PROTOCOL (Platform Core — locked)",
         ""]
for r in proto:
    step = r['Step']
    lines.append(f"Step {step}: {r['Rule']}")
    if r.get('Directions'):
        lines.append(r['Directions'])
    lines.append("")
lines.append("UNIVERSAL RULES")
lines.append("")
for r in rules:
    lines.append(f"- {r['Rule']}: {r['Statement']}")
body = "\n".join(lines)
body = body.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')
ts = body + "\n`;\n"
os.makedirs(os.path.join(ROOT, 'supabase', 'functions', '_shared'), exist_ok=True)
open(os.path.join(ROOT, 'supabase', 'functions', '_shared', 'extraction-protocol.ts'), 'w', encoding='utf-8').write(ts)
print(f"extraction-protocol.ts: {len(proto)} steps + {len(rules)} rules")
