# ── 4. risk_definitions ─────────────────────────────────────────────────────
rows = []
for r in ae['Deal Risk Taxonomy']:
    ev = r.get('Evidence Type & Signals (STATED = quote-backed; GAP = computable absence)') or ''
    types = []
    if re.search(r'\bSTATED\b', ev, re.I):
        types.append('stated')
    if re.search(r'\bGAP\b', ev, re.I):
        types.append('gap')
    if not types:
        types = ['stated']
    rows.append("(" + ", ".join([
        q(r['risk_key']), q(r['Plain-Language Name (UI)']), q(r.get('Methodology Anchor (internal only)')),
        q(r.get('Definition')), q(ev),
        "ARRAY[" + ",".join(q(t) for t in types) + "]::text[]",
        q(r.get('Severity Rubric')), q(r.get('Example')), 'true']) + ")")
sql = """-- Generated by scripts/seed_extraction_workbooks.py — do not hand-edit.
INSERT INTO public.risk_definitions (risk_key, plain_name, methodology_anchor, definition, evidence_signals, evidence_types, severity_rubric, example, active)
VALUES
""" + ",\n".join(rows) + """
ON CONFLICT (risk_key) DO UPDATE SET
  plain_name = EXCLUDED.plain_name, methodology_anchor = EXCLUDED.methodology_anchor,
  definition = EXCLUDED.definition, evidence_signals = EXCLUDED.evidence_signals,
  evidence_types = EXCLUDED.evidence_types, severity_rubric = EXCLUDED.severity_rubric,
  example = EXCLUDED.example, active = true;
"""
open(os.path.join(OUT, 'seed_risk_definitions.sql'), 'w', encoding='utf-8').write(sql)
