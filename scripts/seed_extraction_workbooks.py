# Seeds the extraction-overhaul reference data from the docs/extraction
# workbooks (via the parsed JSON dumps). Generates idempotent SQL files in
# scripts/generated/ which are applied as Supabase migrations:
#
#   seed_field_definitions.sql  -> custom_field_definitions (platform template,
#                                  org_id NULL), 94 catalog fields with
#                                  payment_methods merged into
#                                  vendor_payment_methods (93 rows)
#   seed_core_entities.sql      -> extraction_definitions (8 entities, scope
#                                  'platform', org_id NULL)
#   seed_metric_taxonomy.sql    -> metric_taxonomy (22 rows)
#   seed_risk_definitions.sql   -> risk_definitions (27 rows)
#   seed_module_reference.sql   -> module_reference (starter list, SKUs mapped
#                                  by name-match against products separately)
#
# Idempotency: every INSERT is ON CONFLICT ... DO UPDATE, so re-running the
# generated SQL converges to the workbook state.
#
# The Universal Rules + Extraction Protocol tabs are emitted as
# supabase/functions/_shared/extraction-protocol.ts (locked Platform Core
# prompt segment).
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARSED = os.path.join(ROOT, 'docs', 'extraction', 'parsed')
OUT = os.path.join(ROOT, 'scripts', 'generated')
os.makedirs(OUT, exist_ok=True)

def load(name):
    return json.load(open(os.path.join(PARSED, name), encoding='utf-8'))

def q(s):
    # SQL string literal with single-quote doubling; None -> NULL
    if s is None or s == '':
        return 'NULL'
    return "'" + str(s).replace("'", "''") + "'"

def jarr(s):
    # Signals cells are newline- or semicolon-delimited phrasings -> jsonb array
    if not s:
        return "'[]'::jsonb"
    parts = [p.strip(' -•') for p in re.split(r'[\n;]+', str(s)) if p.strip(' -•')]
    return q(json.dumps(parts)) + '::jsonb'

sc_defs = load('sc_defs.json')
catalog = {r['Proposed field_key']: r for r in load('sc_catalog.json')['Field Catalog']}
ae = load('ae_defs.json')

# ── 1. custom_field_definitions (platform template scope: org_id NULL) ──────
TYPE_MAP = {'number': 'number', 'text': 'text', 'boolean': 'boolean', 'list': 'multiselect'}
STORAGE_MAP = {
    'company_systems': 'company_systems',
    'existing AE extraction': None,  # resolved per-field below
}
AE_ROUTING = {
    'driver_for_new_erp': 'business_catalysts',
    'problems_to_solve': 'deal_pain_points',
    'success_definition': 'deal_analysis.ideal_solution',
    'ideal_solution': 'deal_analysis.ideal_solution',
}

rows = []
sort = 0
for r in sc_defs['Field Definitions']:
    key = r['field_key']
    if key == 'payment_methods':
        continue  # merged into vendor_payment_methods (one definition)
    cat = catalog.get(key, {})
    stored_in = cat.get('Stored In', 'deal attribute (new)')
    if stored_in == 'company_systems':
        storage_target = 'company_systems'
    elif stored_in == 'existing AE extraction':
        storage_target = AE_ROUTING.get(key)
    else:
        storage_target = None
    ftype = TYPE_MAP.get(cat.get('Value Type', 'text'), 'text')
    sort += 10
    instructions = (r.get('Type & Normalization') or '')
    good, bad = r.get('Good Example') or '', r.get('Bad Example') or ''
    if good:
        instructions += '\nGood example: ' + good
    if bad:
        instructions += '\nBad example: ' + bad
    extra = ''
    if key == 'vendor_payment_methods':
        extra = ' (merged with payment_methods: one definition covers vendor payment rails)'
    rows.append(
        "(NULL, 'deal', "
        + ', '.join([
            q(key),
            q(r['Question']),
            q(ftype),
            q((r['Canonical Definition'] or '')[:500]),   # admin_description (NOT NULL)
            q(r['Section']),
            q((r['Canonical Definition'] or '') + extra),
            q(instructions.strip()),
            jarr(r.get('Positive Signals')),
            jarr(r.get('Negative Signals / Anti-patterns')),
            q(storage_target),
            str(sort),
        ])
        + ', true)'
    )

sql = """-- Generated by scripts/seed_extraction_workbooks.py — do not hand-edit.
-- Platform-template SC field catalog (org_id NULL mirrors the coaches
-- template convention).
CREATE UNIQUE INDEX IF NOT EXISTS idx_cfd_template_field_key
  ON public.custom_field_definitions(entity_type, field_key) WHERE org_id IS NULL;
INSERT INTO public.custom_field_definitions
  (org_id, entity_type, field_key, field_label, field_type, admin_description,
   display_section, ai_context, extraction_instructions, extraction_signals,
   negative_signals, storage_target, sort_order, is_active)
VALUES
""" + ",\n".join(rows) + """
ON CONFLICT (entity_type, field_key) WHERE org_id IS NULL
DO UPDATE SET
  field_label = EXCLUDED.field_label,
  field_type = EXCLUDED.field_type,
  display_section = EXCLUDED.display_section,
  ai_context = EXCLUDED.ai_context,
  extraction_instructions = EXCLUDED.extraction_instructions,
  extraction_signals = EXCLUDED.extraction_signals,
  negative_signals = EXCLUDED.negative_signals,
  storage_target = EXCLUDED.storage_target,
  sort_order = EXCLUDED.sort_order,
  is_active = true;
"""
open(os.path.join(OUT, 'seed_field_definitions.sql'), 'w', encoding='utf-8').write(sql)
print(f"field definitions: {len(rows)} rows")

